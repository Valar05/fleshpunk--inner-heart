    payload = read_json(FOLLOWUPS_PATH)
    phrases: list[str] = []
    for phrase in payload.get("phrases", []):
        phrase_text = normalize_tts_text(str(phrase))
        if phrase_text and phrase_text not in phrases:
            phrases.append(phrase_text)
    return phrases


